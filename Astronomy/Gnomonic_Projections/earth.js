export const DEFAULT_EARTH_PRESET = 'outlines';
const RENDER_SIZE = 256;
// Source SVG is a true vector file, but Modes B/C/D's per-face pre-renderers
// and Mode A's 3D globe texture need a raster. Mode A-2 now uses per-face
// vector path rendering directly (so it doesn't sample this raster), so this
// only needs enough resolution for the 256x256 per-face canvas sampling done
// by preRenderEarthFaces — 2048x1024 RGBA = ~8 MB getImageData, fast to
// rasterize and process on first load.
const SVG_RASTER_W = 2048;
const SVG_RASTER_H = 1024;
const ARCTIC_LAT_DEG = 66.5;
const POLAR_ICE_RGBA = (a) => `rgba(200, 216, 232, ${a})`;

export async function loadEarthImage(presetIdOrUrl = DEFAULT_EARTH_PRESET) {
    // Accept a registry ID, a raw URL, or undefined (=> default preset).
    const preset = (typeof presetIdOrUrl === 'string' && EARTH_PRESETS[presetIdOrUrl])
        ? EARTH_PRESETS[presetIdOrUrl]
        : { url: presetIdOrUrl };
    if (preset.dedupeEdges) {
        // SVG's inline CSS can't selectively hide country-shared borders, so we
        // bypass loadAndStyleEarthSvg and render the deduplicated paths to a
        // fresh equirectangular canvas with our own renderer.
        const pathData = await loadEarthSvgPaths(preset.id);
        const style = PRESET_PATH_STYLES[preset.id] || PRESET_PATH_STYLES.bare;
        return rasterizeContinentsImage(pathData, style, SVG_RASTER_W, SVG_RASTER_H);
    }
    if (preset.svgStyle) return loadAndStyleEarthSvg(preset);
    return loadRasterImage(preset.url);
}

// Render the deduplicated SVG paths (from loadEarthSvgPaths with dedupeEdges)
// to a global equirectangular canvas. Segments whose canonical-key appears in
// multiple country paths (i.e. shared country borders) are skipped, leaving
// only the coastline / land-water boundaries.
function rasterizeContinentsImage(pathData, style, w, h) {
    const canvas = document.createElement('canvas');
    canvas.width = w; canvas.height = h;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = style.bgColor || '#ffffff';
    ctx.fillRect(0, 0, w, h);
    ctx.strokeStyle = style.stroke || '#5c3d2e';
    ctx.lineWidth = (style.strokeWidthPx || 1.0) * (w / 4096); // scale stroke with raster width
    ctx.lineJoin = 'round';
    ctx.lineCap  = 'round';
    const proj = (lat, lon) => ({
        x: (lon / (2 * Math.PI) + 0.5) * w,
        y: (0.5 - lat / Math.PI) * h,
    });
    for (const path of pathData.paths) {
        ctx.beginPath();
        let penDown = false;
        for (const pt of path.points) {
            const p = proj(pt.lat, pt.lon);
            if (!penDown || pt.move || pt.skipFromPrev) {
                ctx.moveTo(p.x, p.y);
                penDown = true;
            } else {
                ctx.lineTo(p.x, p.y);
            }
        }
        ctx.stroke();
    }
    // The 3D Mode A globe sphere uses the texture's `naturalWidth/Height` to
    // size its data canvas — mimic the existing rasterisation by exposing them.
    Object.defineProperty(canvas, 'naturalWidth',  { value: w });
    Object.defineProperty(canvas, 'naturalHeight', { value: h });
    return canvas;
}

function loadRasterImage(url) {
    return new Promise((resolve, reject) => {
        const img = new Image();
        img.crossOrigin = 'anonymous';
        img.onload = () => resolve(img);
        img.onerror = () => reject(new Error(`Failed to load Earth texture: ${url}`));
        img.src = url;
    });
}

async function loadAndStyleEarthSvg(preset) {
    const { url, svgStyle, paintArctic, arcticAlpha = 0.55 } = preset;
    const resp = await fetch(url);
    if (!resp.ok) throw new Error(`Earth SVG fetch ${resp.status}: ${url}`);
    let svgText = await resp.text();
    svgText = svgText.replace(/<style[^>]*>[\s\S]*?<\/style>/, svgStyle);
    // Force the SVG to render at our target raster size. The source declares
    // width/height=360x180; without this override, some browsers rasterize at
    // that native size and the canvas upscale would be fuzzy and clip strokes.
    svgText = svgText.replace(/<svg\b([^>]*)>/, (_m, attrs) => {
        const noSize = attrs.replace(/\s(?:width|height)="[^"]*"/g, '');
        return `<svg${noSize} width="${SVG_RASTER_W}" height="${SVG_RASTER_H}">`;
    });
    const blob = new Blob([svgText], { type: 'image/svg+xml' });
    const blobUrl = URL.createObjectURL(blob);
    try {
        const img = await new Promise((resolve, reject) => {
            const i = new Image();
            i.onload = () => resolve(i);
            i.onerror = () => reject(new Error('Styled Earth SVG: Image load failed'));
            i.src = blobUrl;
        });
        const c = document.createElement('canvas');
        c.width = SVG_RASTER_W;
        c.height = SVG_RASTER_H;
        const ctx = c.getContext('2d');
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, SVG_RASTER_W, SVG_RASTER_H);
        ctx.drawImage(img, 0, 0, SVG_RASTER_W, SVG_RASTER_H);
        if (paintArctic) {
            const arcticY = SVG_RASTER_H * (90 - ARCTIC_LAT_DEG) / 180;
            ctx.fillStyle = POLAR_ICE_RGBA(arcticAlpha);
            ctx.fillRect(0, 0, SVG_RASTER_W, arcticY);
        }
        Object.defineProperty(c, 'naturalWidth',  { value: SVG_RASTER_W });
        Object.defineProperty(c, 'naturalHeight', { value: SVG_RASTER_H });
        return c;
    } finally {
        URL.revokeObjectURL(blobUrl);
    }
}

