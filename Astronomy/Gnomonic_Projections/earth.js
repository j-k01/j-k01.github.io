// Load an equirectangular Earth texture and pre-render its gnomonic
// projection onto each polyhedron face. Result: one offscreen canvas
// per face, with the Earth's surface mapped through the face plane and
// clipped to the face polygon (triangle/square/pentagon depending on
// the polyhedron type).
//
// The display side (modes B / C / D) maps each offscreen canvas onto the
// destination polygon with a 2x3 affine via ctx.setTransform.

// Earth representation registry. Each entry is either:
//   - a styled SVG preset (svgStyle present) that we rewrite on load, or
//   - a raster URL (svgStyle absent) loaded as-is.
// The blank-equirectangular SVG (Natural Earth-derived; CC0) has one
// <path> per country wrapped in <g class="country XXX"> where XXX is the
// ISO 3166-1 alpha-3 code, so we can target Antarctica/Greenland by class.
const BLANKMAP_URL = './assets/BlankMap-Equirectangular.svg';

const OUTLINE_STYLE = `<style type="text/css">
    .country { fill: none; stroke: #5c3d2e; stroke-width: 0.25; stroke-linejoin: round; }
    .country.ATA, .country.GRL { fill: #d6c89c; fill-opacity: 0.7; stroke: #5c3d2e; stroke-width: 0.25; }
</style>`;

// Bare-outlines variant: country borders only, no Antarctica/Greenland fill,
// no Arctic ice strip. Reads as a clean line-only world map suitable for
// overlay with elevation contours.
const BARE_OUTLINE_STYLE = `<style type="text/css">
    .country { fill: none; stroke: #5c3d2e; stroke-width: 0.25; stroke-linejoin: round; }
</style>`;

// Solid land - continents read as unified blobs (no inter-country borders).
// Antarctica and Greenland get the same ice fill the Arctic strip uses, so
// the polar regions look like a single ice cap.
const SOLID_STYLE = `<style type="text/css">
    .country { fill: #5a7a4a; stroke: none; }
    .country.ATA, .country.GRL { fill: #c8d8e8; stroke: none; }
</style>`;

